export function buildAliceSentenceWords({ sentence, paragraphId, chapterId }: BuildWordsOptions): ReaderWord[] {
  return sentence.text.split(/\s+/).filter(Boolean).map((text, index) => {
    const normalized = normalizeReaderToken(text);
    const isPunctuation = normalized.length === 0;
    const lexical = isPunctuation ? punctuationEntry() : getLexicalEntry(normalized);
    const contextualTranslation = normalized ? getContextualTranslation(normalized, sentence) : undefined;
    const phraseContext = normalized ? phraseOverrides[normalized]?.[sentence.id] : undefined;

    return {
      id: `${sentence.id}-w${index + 1}`,
      text,
      normalized,
      lemma: lexical.lemma,
      translation: contextualTranslation ?? lexical.translation,
      contextualTranslation,
      commonTranslations: lexical.commonTranslations,
      phrase: phraseContext?.phrase,
      phraseTranslation: phraseContext?.phraseTranslation,
      transcription: lexical.transcription,
      partOfSpeech: lexical.partOfSpeech,
      sentenceId: sentence.id,
      paragraphId,
      chapterId,
      lexicalEntryId: isPunctuation ? undefined : lexicalEntryId(lexical),
      isProperNoun: lexical.isProperNoun,
      isArchaic: lexical.isArchaic,
      isPunctuation,
    };
  });
}

export const buildAliceChapterOneSentenceWords = buildAliceSentenceWords;

function entry(
  lemma: string,
  translation: string,
  transcription: string,
  partOfSpeech: PartOfSpeech,
  commonTranslations?: string[],
  isProperNoun = false,
  isArchaic = false,
): LexicalEntry {
  return { lemma, translation, transcription, partOfSpeech, commonTranslations, isProperNoun, isArchaic };
}

function getLexicalEntry(normalized: string): LexicalEntry {
  const override = lexicalOverrides[normalized];
  if (override) return override;

  const lemma = lemmaOverrides[normalized] ?? inferLemma(normalized);
  const translation = translations[normalized] ?? translations[lemma] ?? supplementalTranslations[normalized] ?? supplementalTranslations[lemma] ?? "перевод по контексту";
  const partOfSpeech = partOfSpeechOverrides[normalized] ?? inferPartOfSpeech(normalized);
  return entry(lemma, translation, ipaOverrides[normalized] ?? ipaOverrides[lemma] ?? "", partOfSpeech);
}

function getContextualTranslation(normalized: string, sentence: ReaderSentence) {
  const override = contextualOverrides[normalized]?.[sentence.id];
  if (override) return override;

  const text = sentence.text.toLowerCase();

  if (normalized === "right") {
    if (text.includes("right size") || text.includes("right way")) return "правильный";
    if (text.includes("right through")) return "прямо";
    return "как раз / правый";
  }

  if (normalized === "mean" || normalized === "means" || normalized === "meant") {
    if (text.includes("what do you mean") || text.includes("what does it mean")) return "значить";
    return "иметь в виду";
  }

  if (normalized === "sentence") {
    if (text.includes("sentence first") || text.includes("execution")) return "приговор";
    return "предложение";
  }

  if (normalized === "court") {
    if (text.includes("king") || text.includes("queen") || text.includes("jury") || text.includes("trial")) return "суд";
    return "двор";
  }

  if (normalized === "still") {
    if (text.includes("stood still") || text.includes("quite still")) return "неподвижно";
    return "всё ещё";
  }

  return undefined;
}

function punctuationEntry(): LexicalEntry {
  return entry("", "", "", "noun");
}

function normalizeReaderToken(text: string) {
  const cleaned = text.replace(/_/g, "").replace(/[“”‘]/g, "").replace(/'/g, "’").toLowerCase();
  const match = cleaned.match(/[a-z]+(?:[’'][a-z]+)?(?:-[a-z]+(?:[’'][a-z]+)?)*|[0-9]+/);
  return match?.[0].replace(/'/g, "’") ?? "";
}

function inferLemma(normalized: string) {
  if (normalized.endsWith("ies") && normalized.length > 4) return `${normalized.slice(0, -3)}y`;
  if (normalized.endsWith("ing") && normalized.length > 5) return normalized.slice(0, -3);
  if (normalized.endsWith("ed") && normalized.length > 4) return normalized.slice(0, -2);
  if (normalized.endsWith("s") && normalized.length > 3 && !normalized.endsWith("ss")) return normalized.slice(0, -1);
  return normalized;
}

function inferPartOfSpeech(normalized: string): PartOfSpeech {
  if (normalized.endsWith("ly")) return "adverb";
  if (normalized.endsWith("ing") || normalized.endsWith("ed")) return "verb";
  if (["able", "al", "ful", "ic", "ive", "less", "ous"].some((suffix) => normalized.endsWith(suffix))) return "adjective";
  return "noun";
}

function lexicalEntryId(lexical: LexicalEntry) {
  return `${lexical.lemma.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${lexical.partOfSpeech.replace(/\s+/g, "-")}`;
}
